"""Run from anywhere:  python scripts/make-themes.py
Writes src/themes.css: the Dark and Midnight Purple themes.

How it works: Tailwind v4 draws every colour class from a CSS variable
(bg-slate-50 -> var(--color-slate-50)). A theme redefines those variables:
  * the grey scale (slate, gray) is turned round: light greys become dark
    surfaces, dark greys become light text;
  * the pale tints (red-50, amber-100, ...) become see-through washes;
  * Midnight Purple also turns the indigo accent into purple.
A few classes cannot follow a variable alone and are recoloured directly:
bg-white (shares its variable with text-white), the dark backdrops behind
dialogs, and coloured text (text-red-700 must turn LIGHT on a dark page,
while bg-red-700 stays a solid colour)."""

HUES = {  # 300 (strong text), 400 (soft text), 500 (washes)
    'red': ('#fca5a5', '#f87171', '#ef4444'),
    'amber': ('#fcd34d', '#fbbf24', '#f59e0b'),
    'emerald': ('#6ee7b7', '#34d399', '#10b981'),
    'indigo': ('#a5b4fc', '#818cf8', '#6366f1'),
    'sky': ('#7dd3fc', '#38bdf8', '#0ea5e9'),
    'blue': ('#93c5fd', '#60a5fa', '#3b82f6'),
    'purple': ('#d8b4fe', '#c084fc', '#a855f7'),
    'violet': ('#c4b5fd', '#a78bfa', '#8b5cf6'),
    'green': ('#86efac', '#4ade80', '#22c55e'),
    'rose': ('#fda4af', '#fb7185', '#f43f5e'),
    'orange': ('#fdba74', '#fb923c', '#f97316'),
    'yellow': ('#fde047', '#facc15', '#eab308'),
    'teal': ('#5eead4', '#2dd4bf', '#14b8a6'),
    'pink': ('#f9a8d4', '#f472b6', '#ec4899'),
    'fuchsia': ('#f0abfc', '#e879f9', '#d946ef'),
    'cyan': ('#67e8f9', '#22d3ee', '#06b6d4'),
    'lime': ('#bef264', '#a3e635', '#84cc16'),
}

# The grey scale, turned round. page = slate-50 (the app's background),
# card = what bg-white becomes.
GREYS = {
    'dark': {
        'card': '#111827',
        '50': '#0b1120', '100': '#1a2233', '200': '#263041', '300': '#344054', '400': '#7a8699',
        '500': '#94a1b4', '600': '#a9b4c4', '700': '#cbd5e1', '800': '#dfe5ee', '900': '#f1f5f9', '950': '#f8fafc',
    },
    'purple': {
        'card': '#1f1440',
        '50': '#150c2b', '100': '#2a1c52', '200': '#36265f', '300': '#4a3878', '400': '#8f80b8',
        '500': '#a99cd0', '600': '#bcb1de', '700': '#d6cdef', '800': '#e6e0f7', '900': '#f4f0ff', '950': '#faf8ff',
    },
}

# Midnight Purple's accent: everything the app paints indigo becomes purple.
PURPLE_ACCENT = {'300': '#d8b4fe', '400': '#c084fc', '500': '#a855f7', '600': '#9333ea', '700': '#7e22ce', '800': '#6b21a8', '900': '#581c87', '950': '#3b0764'}

STOPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']


def esc(cls):
    return cls.replace(':', '\\:').replace('/', '\\/').replace('[', '\\[').replace(']', '\\]').replace('.', '\\.')


out = []
w = out.append
w('/* Generated by scripts/make-themes.py: the Dark and Midnight Purple themes. Edit that file and run it again. */')
w('/*')
w('   The saved choice is applied by src/lib/theme.ts (and index.html, before the first paint):')
w('   html[data-theme="dark" | "purple"], with the class sa-night on both. */')
w('')

for theme, g in GREYS.items():
    w(f'html[data-theme="{theme}"] {{')
    w(f'  --sa-card: {g["card"]};')
    w(f'  --sa-page: {g["50"]};')
    for s in STOPS:
        w(f'  --color-slate-{s}: {g[s]};')
        w(f'  --color-gray-{s}: {g[s]};')
    for h, (strong, soft, base) in HUES.items():
        b = PURPLE_ACCENT['500'] if (theme == 'purple' and h == 'indigo') else base
        w(f'  --color-{h}-50: color-mix(in oklab, {b} 14%, transparent);')
        w(f'  --color-{h}-100: color-mix(in oklab, {b} 22%, transparent);')
        w(f'  --color-{h}-200: color-mix(in oklab, {b} 34%, transparent);')
        if theme == 'purple' and h == 'indigo':
            st, so = HUES['purple'][0], HUES['purple'][1]
        else:
            st, so = strong, soft
        w(f'  --sa-tx-{h}: {st};')
        w(f'  --sa-txs-{h}: {so};')
    if theme == 'purple':
        for s, v in PURPLE_ACCENT.items():
            w(f'  --color-indigo-{s}: {v};')
    w('}')
    w('')

N = 'html.sa-night'
w(f'{N} body {{ background-color: var(--sa-page); }}')
w('')
w('/* White surfaces become the theme\'s card colour; white text stays white. */')
w(f'{N} .bg-white, {N} .hover\\:bg-white:hover, {N} .focus\\:bg-white:focus {{ background-color: var(--sa-card); }}')
w(f'{N} .bg-white\\/95 {{ background-color: color-mix(in oklab, var(--sa-card) 95%, transparent); }}')
w(f'{N} .ring-white {{ --tw-ring-color: var(--sa-card); }}')
w(f'{N} .ring-offset-white {{ --tw-ring-offset-color: var(--sa-card); }}')
w('')
w('/* The shade behind dialogs and the phone menu stays dark. */')
for a in (40, 50, 60, 80):
    w(f'{N} .bg-slate-900\\/{a} {{ background-color: rgb(0 0 0 / {a + 10}%); }}')
w(f'{N} .hover\\:bg-slate-900\\/80:hover {{ background-color: color-mix(in oklab, var(--color-slate-900) 80%, transparent); }}')
w('')
w('/* White text on solid red stays white. */')
w(f'{N} .bg-red-500.text-slate-50 {{ color: #ffffff; }}')
w('')
w('/* Coloured text turns light on a dark page: strong for 600 and up, softer for 400-500. */')
sel = []
for h in HUES:
    for s in ['600', '700', '800', '900', '950']:
        cls = f'text-{h}-{s}'
        sel.append((f'{N} .{esc(cls)}', f'var(--sa-tx-{h})'))
        sel.append((f'{N} .{esc("hover:" + cls)}:hover', f'var(--sa-tx-{h})'))
        sel.append((f'{N} .group:hover .{esc("group-hover:" + cls)}', f'var(--sa-tx-{h})'))
        for a in (70, 80):
            sel.append((f'{N} .{esc(cls + "/" + str(a))}', f'color-mix(in oklab, var(--sa-tx-{h}) {a}%, transparent)'))
    for s in ['400', '500']:
        cls = f'text-{h}-{s}'
        sel.append((f'{N} .{esc(cls)}', f'var(--sa-txs-{h})'))
        sel.append((f'{N} .{esc("hover:" + cls)}:hover', f'var(--sa-txs-{h})'))
        sel.append((f'{N} .group:hover .{esc("group-hover:" + cls)}', f'var(--sa-txs-{h})'))
        for a in (70, 80):
            sel.append((f'{N} .{esc(cls + "/" + str(a))}', f'color-mix(in oklab, var(--sa-txs-{h}) {a}%, transparent)'))
for selector, value in sel:
    w(f'{selector} {{ color: {value}; }}')
w('')
w('/* Soft coloured shadows would glow on a dark page. */')
w(f'{N} [class*="shadow-indigo-"] {{ --tw-shadow-color: rgb(0 0 0 / 35%); }}')
w('')
w('/* Scrollbars, date pickers and drop-down lists drawn dark by the browser. */')
w(f'{N} {{ color-scheme: dark; }}')

css = '\n'.join(out) + '\n'
import os
target = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'themes.css')
open(target, 'w', encoding='utf-8').write(css)
print(len(out), 'lines,', len(css) // 1024, 'KB')
